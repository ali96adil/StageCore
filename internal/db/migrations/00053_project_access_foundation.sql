DROP INDEX IF EXISTS project_user_access_audit_project_idx;
DROP TABLE IF EXISTS project_user_access_audit;
DROP INDEX IF EXISTS project_user_capabilities_user_idx;
DROP TABLE IF EXISTS project_user_capabilities;
DROP INDEX IF EXISTS project_user_memberships_user_idx;
DROP TABLE IF EXISTS project_user_memberships;

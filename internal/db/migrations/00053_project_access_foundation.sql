-- +goose Up
-- SC-024: Project memberships and granular capability grants. Metadata only.
-- NO automatic migration of global roles to Project memberships: default
-- for non-OWNER users is no access once comprehensive enforcement is enabled.
-- Enforcing the policy through all Hub routes is a separate audited phase.
CREATE TABLE project_user_memberships (
    project_id TEXT NOT NULL REFERENCES projects(project_id) ON DELETE RESTRICT,
    user_id TEXT NOT NULL REFERENCES local_users(user_id) ON DELETE RESTRICT,
    granted_by_user_id TEXT NOT NULL REFERENCES local_users(user_id) ON DELETE RESTRICT,
    created_at_us INTEGER NOT NULL CHECK(created_at_us > 0),
    updated_at_us INTEGER NOT NULL CHECK(updated_at_us > 0),
    PRIMARY KEY (project_id, user_id)
);

CREATE INDEX project_user_memberships_user_idx
ON project_user_memberships(user_id, project_id);

CREATE TABLE project_user_capabilities (
    project_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    capability TEXT NOT NULL CHECK(capability IN (
        'project.view', 'project.edit', 'project.rename',
        'media.read', 'media.upload', 'media.manage',
        'cue.edit', 'snapshot.publish', 'rehearsal.control',
        'show.go', 'show.enter_exit', 'device.configure', 'project.export'
    )),
    PRIMARY KEY (project_id, user_id, capability),
    FOREIGN KEY (project_id, user_id)
        REFERENCES project_user_memberships(project_id, user_id) ON DELETE CASCADE
);

CREATE INDEX project_user_capabilities_user_idx
ON project_user_capabilities(user_id, project_id, capability);

-- Immutable record of every grant set/replacement/revocation. JSON contents
-- are generated by the Owner-only service after validating the exact allowlist.
CREATE TABLE project_user_access_audit (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    project_id TEXT NOT NULL REFERENCES projects(project_id) ON DELETE RESTRICT,
    user_id TEXT NOT NULL REFERENCES local_users(user_id) ON DELETE RESTRICT,
    actor_user_id TEXT NOT NULL REFERENCES local_users(user_id) ON DELETE RESTRICT,
    operation TEXT NOT NULL CHECK(operation IN ('GRANT_REPLACE', 'REVOKE')),
    before_capabilities_json TEXT NOT NULL,
    after_capabilities_json TEXT NOT NULL,
    created_at_us INTEGER NOT NULL CHECK(created_at_us > 0)
);

CREATE INDEX project_user_access_audit_project_idx
ON project_user_access_audit(project_id, created_at_us DESC, id DESC);

